function thermometerDiagram(){
  const canvas=document.createElement('canvas');
  canvas.width=480;
  canvas.height=205;
  const ctx=canvas.getContext('2d');
  if(!ctx)return '';
  ctx.fillStyle='#ecfeff';
  ctx.fillRect(0,0,480,205);
  ctx.fillStyle='#164e63';
  ctx.font='bold 18px sans-serif';
  ctx.fillText('Температура біля школи, °C',25,28);
  ctx.font='15px sans-serif';
  const measurements=[['8:00',12],['12:00',18],['16:00',15]];
  for(const [index,[time,value]] of measurements.entries()){
    const y=47+index*49;
    ctx.fillStyle='#164e63';
    ctx.fillText(time,25,y+19);
    ctx.fillStyle=['#0e7490','#0369a1','#2563eb'][index];
    ctx.fillRect(90,y,16*value,25);
    ctx.fillStyle='#164e63';
    ctx.fillText(value+'°',102+16*value,y+18);
  }
  return canvas.toDataURL('image/png');
}

